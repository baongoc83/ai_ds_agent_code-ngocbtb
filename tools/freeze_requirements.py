#!/usr/bin/env python
"""Generate requirements-lock.txt from the CURRENT (known-good) environment.

Walks the dependency graph starting at the direct dependencies listed in
requirements.txt and pins every package reached —
direct and transitive — to the version installed right now. Unrelated packages
that happen to live in the same interpreter are NOT included (unlike pip freeze).

    py -3.12 tools/freeze_requirements.py          # rewrite requirements-lock.txt
    py -3.12 tools/freeze_requirements.py --check  # exit 1 if the lock is stale

Run it after deliberately upgrading a dependency in the reference environment.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import platform
import re
import sys
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

REPO = Path(__file__).resolve().parents[1]
# requirements-dev.txt is pinned by hand (test tooling never touches artifacts)
SOURCES = ["requirements.txt"]


def _direct(path: Path) -> list:
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        out.append(Requirement(line))
    return out


def resolve() -> dict:
    env = default_environment()
    seen: dict = {}
    stack = []
    for src in SOURCES:
        p = REPO / src
        if p.exists():
            stack += [(r, None) for r in _direct(p)]
    while stack:
        req, extra = stack.pop()
        if req.marker and not req.marker.evaluate({**env, "extra": extra or ""}):
            continue
        name = canonicalize_name(req.name)
        try:
            dist = md.distribution(req.name)
        except md.PackageNotFoundError:
            sys.exit(f"ERROR: {req.name} is required but not installed in this environment")
        new_extras = set(req.extras) - seen.get(name, (None, set()))[1]
        if name in seen and not new_extras:
            continue
        extras = seen.get(name, (None, set()))[1] | set(req.extras)
        seen[name] = (dist.version, extras)
        for sub in dist.requires or []:
            r = Requirement(sub)
            for ex in [""] + sorted(extras):
                if not r.marker or r.marker.evaluate({**env, "extra": ex}):
                    stack.append((r, ex))
                    break
    return {n: v for n, (v, _) in seen.items()}


def render(pins: dict) -> str:
    head = [
        "# AUTO-GENERATED by tools/freeze_requirements.py — do not edit by hand.",
        f"# Reference environment: Python {platform.python_version()} on {platform.system()} {platform.machine()}",
        "# Every direct AND transitive dependency, pinned to the exact version the",
        "# reference runs were produced with. Install with:",
        "#     pip install -r requirements-lock.txt",
        "",
    ]
    return "\n".join(head + [f"{n}=={v}" for n, v in sorted(pins.items())]) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 when requirements-lock.txt is stale")
    args = ap.parse_args()
    text = render(resolve())
    lock = REPO / "requirements-lock.txt"
    strip = lambda s: re.sub(r"^#.*\n", "", s, flags=re.M)  # noqa: E731 — ignore the header
    if args.check:
        ok = lock.exists() and strip(lock.read_text(encoding="utf-8")) == strip(text)
        print("lock is up to date" if ok else "lock is STALE — run tools/freeze_requirements.py")
        return 0 if ok else 1
    lock.write_text(text, encoding="utf-8")
    print(f"wrote {lock} ({text.count('==')} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
